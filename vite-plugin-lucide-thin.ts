import fs from 'node:fs';
import path from 'node:path';
import type { Plugin } from 'vite';

const IMPORT_RE = /import\s+(?:type\s+)?\{([^}]+)\}\s+from\s+['"]@lucide\/vue['"]/g;
const TYPE_ONLY = new Set(['LucideIcon', 'LucideProps']);

function walk(dir: string, out: string[] = []): string[] {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) {
            walk(full, out);
            continue;
        }
        if (/\.(vue|ts|tsx|js|jsx)$/.test(entry.name) && entry.name !== 'lucide-icons.ts') {
            out.push(full);
        }
    }
    return out;
}

function collectUsedIcons(srcRoot: string): Set<string> {
    const names = new Set<string>();
    for (const file of walk(srcRoot)) {
        const code = fs.readFileSync(file, 'utf8');
        for (const match of code.matchAll(IMPORT_RE)) {
            for (const part of match[1].split(',')) {
                let name = part.trim();
                if (!name) continue;
                if (name.startsWith('type ')) name = name.slice(5).trim();
                if (name.includes(' as ')) name = name.split(/\s+as\s+/)[0].trim();
                if (TYPE_ONLY.has(name)) continue;
                names.add(name);
            }
        }
    }
    return names;
}

function mapExportsToFiles(barrelPath: string): Map<string, string> {
    const map = new Map<string, string>();
    const barrel = fs.readFileSync(barrelPath, 'utf8');
    for (const line of barrel.split(/\r?\n/)) {
        const match = line.match(/export \{([^}]+)\} from '\.\/icons\/([^']+)'/);
        if (!match) continue;
        const file = match[2];
        for (const part of match[1].split(',')) {
            const nameMatch = part.match(/default as (\w+)/);
            if (nameMatch) map.set(nameMatch[1], file);
        }
    }
    return map;
}

function generateThinBarrel(projectRoot: string): string {
    const srcRoot = path.join(projectRoot, 'resources/js');
    const outFile = path.join(srcRoot, 'lib/lucide-icons.ts');
    const barrelPath = path.join(projectRoot, 'node_modules/@lucide/vue/dist/esm/lucide-vue.mjs');
    const iconsDir = path.join(projectRoot, 'node_modules/@lucide/vue/dist/esm/icons');

    if (!fs.existsSync(barrelPath)) {
        throw new Error('[@lucide/vue thin] Package not installed. Run npm ci first.');
    }

    const used = collectUsedIcons(srcRoot);
    const exportMap = mapExportsToFiles(barrelPath);
    const byFile = new Map<string, string[]>();
    const missingExports: string[] = [];
    const missingFiles: string[] = [];

    for (const name of [...used].sort()) {
        const file = exportMap.get(name);
        if (!file) {
            missingExports.push(name);
            continue;
        }
        if (!fs.existsSync(path.join(iconsDir, file))) {
            missingFiles.push(`${name} -> ${file}`);
            continue;
        }
        const list = byFile.get(file) ?? [];
        list.push(name);
        byFile.set(file, list);
    }

    if (missingExports.length > 0) {
        throw new Error(`[@lucide/vue thin] Unknown icon exports: ${missingExports.join(', ')}`);
    }
    if (missingFiles.length > 0) {
        throw new Error(
            `[@lucide/vue thin] Icon files missing from node_modules (reinstall @lucide/vue): ${missingFiles.join(', ')}`,
        );
    }

    const lines = [
        '/**',
        ' * AUTO-GENERATED by vite-plugin-lucide-thin. Do not edit by hand.',
        ' * Thin Lucide re-exports so Vite/Rolldown only resolves icons this app uses.',
        ' */',
        "import type { FunctionalComponent, SVGAttributes } from 'vue';",
        '',
        'export interface LucideProps extends Partial<SVGAttributes> {',
        '    size?: string | number;',
        '    strokeWidth?: number | string;',
        '    absoluteStrokeWidth?: boolean;',
        "    'absolute-stroke-width'?: boolean;",
        '}',
        '',
        'export type LucideIcon = FunctionalComponent<LucideProps>;',
        '',
    ];

    for (const file of [...byFile.keys()].sort()) {
        const names = (byFile.get(file) ?? []).sort();
        const asParts = names.map((n) => `default as ${n}`).join(', ');
        lines.push(`export { ${asParts} } from '@lucide/vue/dist/esm/icons/${file}';`);
    }
    lines.push('');

    const next = lines.join('\n');
    const prev = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
    if (prev !== next) {
        fs.mkdirSync(path.dirname(outFile), { recursive: true });
        fs.writeFileSync(outFile, next, 'utf8');
    }

    return outFile;
}

/**
 * Rewrites `@lucide/vue` barrel imports to a generated thin module of only used icons.
 * Prevents Vite 8 / Rolldown from resolving ~2k icon files (and failing if any are missing).
 */
export function lucideThinBarrel(): Plugin {
    let thinBarrelPath = '';

    return {
        name: 'lucide-thin-barrel',
        enforce: 'pre',
        configResolved(config) {
            thinBarrelPath = generateThinBarrel(config.root);
        },
        resolveId(source) {
            if (source === '@lucide/vue') {
                return thinBarrelPath;
            }
            return null;
        },
    };
}
